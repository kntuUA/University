#!/usr/bin/env node
/**
 * Zero-dependency concatenation "build" for a zero-build site.
 *
 * The browser never needs this script: its outputs are committed, so the site
 * still works straight from file:// and GitHub Pages. It only joins small,
 * readable source files into the few files the HTML links:
 *
 *   assets/css/{base,components,features}/*.css + print.css → assets/css/main.css
 *   assets/js/core/*.js                                    → assets/js/boot.js
 *   assets/js/{components,features}/*.js                   → assets/js/app.js
 *
 * Order matters (cascade, boot order) and is declared explicitly below.
 * CSS is copied verbatim; JS bundles drop whole-line comments (see below).
 *
 *   node scripts/build.mjs          write the bundles
 *   node scripts/build.mjs --check  exit 1 if a bundle is stale (used by `npm run lint`)
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');

const css = (banner) => ({
  banner: `/* ${banner}\n   GENERATED by scripts/build.mjs — edit the sources, then run \`npm run build\`. */\n`,
});
const js = (banner) => ({
  banner: `/* ${banner}\n * GENERATED by scripts/build.mjs — edit the sources, then run \`npm run build\`. */\n`,
});

/** Output file → ordered list of sources (paths relative to the output's folder). */
const BUNDLES = {
  'assets/css/main.css': {
    ...css(
      `ЦНТУ — site styles. Sources (cascade order):
   base/      fonts · tokens · reset · utilities · layout
   components/ notice · header · lang-menu · burger · hero · cards · buttons · footer
   base/      responsive          features/ matrix · terminal
   base/      reduced-motion      features/ konami-cat          print.css
   Naming: BEM (block__element--modifier); state: .is-*; JS hook: .js on <html>.
   Logical properties (inline/block) are used so the layout also works in RTL.
   Relative url()s are written for THIS file's folder (assets/css/).`,
    ),
    sources: [
      'base/fonts.css',
      'base/tokens.css',
      'base/reset.css',
      'base/utilities.css',
      'base/layout.css',
      'components/notice.css',
      'components/header.css',
      'components/lang-menu.css',
      'components/burger.css',
      'components/hero.css',
      'components/cards.css',
      'components/buttons.css',
      'components/footer.css',
      'base/responsive.css',
      'features/matrix.css',
      'features/terminal.css',
      'base/reduced-motion.css',
      'features/konami-cat.css',
      'print.css',
    ],
  },
  // Synchronous in <head>: must stay small; order = dependency order.
  'assets/js/boot.js': {
    ...js(`Boot (sync in <head>): window.CNTU core — config, dom, storage, bus,
 * paths, theme (applied before first paint), i18n (language + dictionary).`),
    sources: [
      'core/namespace.js',
      'core/storage.js',
      'core/bus.js',
      'core/paths.js',
      'core/theme.js',
      'core/i18n.js',
    ],
  },
  // Deferred on index.html; order = boot order (language first).
  'assets/js/app.js': {
    ...js(`index.html UI (defer): components, then the easter eggs.`),
    sources: [
      'components/lang-menu.js',
      'components/theme-toggle.js',
      'components/mobile-menu.js',
      'components/header-offset.js',
      'components/nav-highlight.js',
      'components/notice.js',
      'components/footer-year.js',
      'features/matrix.js',
      'features/terminal.js',
      'features/konami-cat.js',
    ],
  },
};

/**
 * JS bundles drop whole-line comments (the sources keep them): boot.js is
 * render-blocking, and every KB counts on a throttled mobile connection.
 * Only lines that START a comment are removed, so code, strings and regexes
 * are never touched; lines inside multi-line template literals are kept as is.
 * @param {string} code
 */
const stripLineComments = (code) => {
  const out = [];
  let inBlock = false;
  let inTemplate = false; // multi-line template literals (HTML/SVG) are kept verbatim
  for (const line of code.split('\n')) {
    const trimmed = line.trim();
    if (inBlock) {
      if (trimmed.includes('*/')) inBlock = false;
      continue;
    }
    if (!inTemplate) {
      if (trimmed.startsWith('//')) continue;
      if (trimmed.startsWith('/*')) {
        inBlock = !trimmed.includes('*/');
        continue;
      }
      if (trimmed === '' && out.at(-1)?.trim() === '') continue;
    }
    const backticks = (line.replace(/'`'/g, '').match(/`/g) ?? []).length;
    if (backticks % 2 === 1) inTemplate = !inTemplate;
    out.push(line);
  }
  return out.join('\n');
};

const render = (out, { banner, sources }) => {
  const dir = dirname(join(ROOT, out));
  const transform = out.endsWith('.js') ? stripLineComments : (text) => text;
  return (
    banner + sources.map((src) => '\n' + transform(readFileSync(join(dir, src), 'utf8'))).join('')
  );
};

let stale = 0;
for (const [out, bundle] of Object.entries(BUNDLES)) {
  const file = join(ROOT, out);
  const next = render(out, bundle);
  const current = existsSync(file) ? readFileSync(file, 'utf8') : '';
  if (current === next) continue;
  if (CHECK) {
    stale += 1;
    console.error(`✗ ${out} is out of date — run \`npm run build\``);
  } else {
    writeFileSync(file, next);
    console.log(`✓ ${out} (${bundle.sources.length} sources)`);
  }
}
if (CHECK && stale) process.exit(1);
if (CHECK) console.log(`build check passed: ${Object.keys(BUNDLES).length} bundles up to date.`);
